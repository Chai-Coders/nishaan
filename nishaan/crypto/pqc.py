"""Post-quantum public-key primitives (NIST FIPS 203 / 204 / 205).

Only NIST-standardised PQC algorithms are exposed here. Classical public-key
algorithms (RSA, ECDH, ECDSA, EdDSA) are deliberately absent from the whole
code base.

Two interchangeable backends are supported:

* ``oqs``  - liboqs via liboqs-python (fast, C implementation). Preferred.
* ``pure`` - pure-Python reference implementations (kyber-py, dilithium-py).
             Slower, but pip-installable anywhere without a C toolchain.

Both backends produce byte-identical FIPS encodings for keys, ciphertexts and
signatures, so a key generated by one can be used by the other (this is
checked in tests/test_crypto.py). Select with NISHAAN_PQC_BACKEND=oqs|pure|auto.
"""
from __future__ import annotations

import os
import warnings
from functools import lru_cache

KEM_ALG = "ML-KEM-768"          # FIPS 203, NIST category 3
SIG_ALG = "ML-DSA-65"           # FIPS 204, NIST category 3
ROOT_SIG_ALG = "SLH-DSA-SHA2-128f"  # FIPS 205, conservative hash-based (CA root), fast variant
ROOT_SIG_FALLBACK = "ML-DSA-87"

_OQS_NAMES = {
    "ML-KEM-768": "ML-KEM-768",
    "ML-KEM-1024": "ML-KEM-1024",
    "ML-DSA-65": "ML-DSA-65",
    "ML-DSA-87": "ML-DSA-87",
    "SLH-DSA-SHA2-128s": "SLH_DSA_PURE_SHA2_128S",
    "SLH-DSA-SHA2-128f": "SLH_DSA_PURE_SHA2_128F",
    "SLH-DSA-SHAKE-128s": "SLH_DSA_PURE_SHAKE_128S",
}

FORBIDDEN = {"RSA", "ECDH", "ECDSA", "EdDSA", "Ed25519", "X25519"}


class PQCUnavailable(RuntimeError):
    pass


@lru_cache(maxsize=1)
def _oqs():
    if os.environ.get("NISHAAN_PQC_BACKEND", "auto") == "pure":
        return None
    try:
        import contextlib
        import io
        import logging
        with warnings.catch_warnings(), contextlib.redirect_stdout(io.StringIO()):
            warnings.simplefilter("ignore")
            import oqs  # type: ignore
        logging.getLogger("oqs.oqs").setLevel(logging.WARNING)
        oqs.get_enabled_sig_mechanisms()
        return oqs
    except Exception:
        if os.environ.get("NISHAAN_PQC_BACKEND") == "oqs":
            raise
        return None


@lru_cache(maxsize=None)
def _pure(alg: str):
    try:
        if alg.startswith("ML-KEM"):
            from kyber_py import ml_kem  # type: ignore
            return getattr(ml_kem, alg.replace("-", "_"))
        if alg.startswith("ML-DSA"):
            from dilithium_py import ml_dsa  # type: ignore
            return getattr(ml_dsa, alg.replace("-", "_"))
    except ImportError as e:  # pragma: no cover
        raise PQCUnavailable(f"no backend available for {alg}: {e}")
    raise PQCUnavailable(f"{alg} has no pure-Python backend; install liboqs-python")


def backend_name() -> str:
    o = _oqs()
    return f"liboqs {o.oqs_version()}" if o else "pure-python (kyber-py / dilithium-py)"


def _check(alg: str):
    if any(f.lower() in alg.lower() for f in FORBIDDEN):
        raise ValueError(f"classical algorithm {alg} is forbidden")
    if alg not in _OQS_NAMES:
        raise ValueError(f"unsupported algorithm {alg}")


def available(alg: str) -> bool:
    _check(alg)
    o = _oqs()
    if o is not None:
        name = _OQS_NAMES[alg]
        return name in o.get_enabled_sig_mechanisms() or name in o.get_enabled_kem_mechanisms()
    try:
        _pure(alg)
        return True
    except PQCUnavailable:
        return False


def root_sig_alg() -> str:
    """Hash-based SLH-DSA for the long-lived CA root when available."""
    return ROOT_SIG_ALG if available(ROOT_SIG_ALG) else ROOT_SIG_FALLBACK


# ---------------------------------------------------------------- KEM

def kem_keygen(alg: str = KEM_ALG) -> tuple[bytes, bytes]:
    _check(alg)
    o = _oqs()
    if o is not None:
        with o.KeyEncapsulation(_OQS_NAMES[alg]) as k:
            pk = k.generate_keypair()
            return bytes(pk), bytes(k.export_secret_key())
    ek, dk = _pure(alg).keygen()
    return ek, dk


def kem_encaps(pk: bytes, alg: str = KEM_ALG) -> tuple[bytes, bytes]:
    """Returns (ciphertext, shared_secret)."""
    _check(alg)
    o = _oqs()
    if o is not None:
        with o.KeyEncapsulation(_OQS_NAMES[alg]) as k:
            ct, ss = k.encap_secret(pk)
            return bytes(ct), bytes(ss)
    ss, ct = _pure(alg).encaps(pk)
    return ct, ss


def kem_decaps(sk: bytes, ct: bytes, alg: str = KEM_ALG) -> bytes:
    _check(alg)
    o = _oqs()
    if o is not None:
        with o.KeyEncapsulation(_OQS_NAMES[alg], secret_key=sk) as k:
            return bytes(k.decap_secret(ct))
    return _pure(alg).decaps(sk, ct)


# ---------------------------------------------------------------- signatures

def sig_keygen(alg: str = SIG_ALG) -> tuple[bytes, bytes]:
    _check(alg)
    o = _oqs()
    if o is not None:
        with o.Signature(_OQS_NAMES[alg]) as s:
            pk = s.generate_keypair()
            return bytes(pk), bytes(s.export_secret_key())
    return _pure(alg).keygen()


def sign(sk: bytes, msg: bytes, ctx: bytes = b"", alg: str = SIG_ALG) -> bytes:
    _check(alg)
    o = _oqs()
    if o is not None:
        with o.Signature(_OQS_NAMES[alg], secret_key=sk) as s:
            return bytes(s.sign_with_ctx_str(msg, ctx))
    return _pure(alg).sign(sk, msg, ctx=ctx)


def verify(pk: bytes, msg: bytes, sig: bytes, ctx: bytes = b"", alg: str = SIG_ALG) -> bool:
    _check(alg)
    try:
        o = _oqs()
        if o is not None:
            with o.Signature(_OQS_NAMES[alg]) as s:
                return bool(s.verify_with_ctx_str(msg, sig, ctx, pk))
        return bool(_pure(alg).verify(pk, msg, sig, ctx=ctx))
    except Exception:
        return False
